// Чистка текста от невидимых символов: при копировании из чатов и сайтов в текст попадают символы нулевой ширины,
// управляющие знаки направления письма, скрытые «теги» и необычные пробелы. На экране их не видно, но они остаются
// в Документе и на площадке. Обычный неразрывный пробел (U+00A0) не трогаем — он нужен в русской типографике.
const DROP = /[​-‍⁠-⁤﻿­᠎‎‏‪-‮⁦-⁩͏]|\uDB40[\uDC00-\uDC7F]|\uDB40[\uDD00-\uDDEF]/g; // \uDB40… — скрытые теги U+E0000–E007F и селекторы U+E0100–E01EF
const SPACE = /[ -   　]/g; // «особые» пробелы → обычный

// → { text, n }: n — сколько символов убрано или заменено
export function cleanText(s) {
  let n = 0;
  const text = String(s ?? '').replace(DROP, () => { n++; return ''; }).replace(SPACE, () => { n++; return ' '; });
  return { text, n };
}
export const hasHidden = (s) => { DROP.lastIndex = 0; SPACE.lastIndex = 0; return DROP.test(s) || SPACE.test(s); };
// «Убрала 3 невидимых символа»
export function cleanedMsg(n) {
  const m = n % 10, h = n % 100, w = m === 1 && h !== 11 ? 'невидимый символ' : m >= 2 && m <= 4 && (h < 12 || h > 14) ? 'невидимых символа' : 'невидимых символов';
  return `Убрала ${n} ${w}`;
}
